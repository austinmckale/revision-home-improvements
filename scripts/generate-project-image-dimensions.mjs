import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, extname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const publicDirectory = resolve(projectRoot, "public");
const projectDirectory = resolve(publicDirectory, "images/projects");
const outputFile = resolve(projectRoot, "src/content/projectImageDimensions.ts");
const rasterExtensions = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif"]);

async function findRasterImages(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const filename = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await findRasterImages(filename)));
    else if (entry.isFile() && rasterExtensions.has(extname(entry.name).toLowerCase())) files.push(filename);
  }
  return files;
}

const entries = [];
for (const filename of (await findRasterImages(projectDirectory)).sort()) {
  const metadata = await sharp(filename).metadata();
  const rotated = metadata.orientation >= 5 && metadata.orientation <= 8;
  const { width, height } = metadata.autoOrient ?? {
    width: rotated ? metadata.height : metadata.width,
    height: rotated ? metadata.width : metadata.height,
  };

  if (!Number.isInteger(width) || width <= 0 || !Number.isInteger(height) || height <= 0) {
    throw new Error(`Missing image dimensions: ${filename}`);
  }

  const src = `/${relative(publicDirectory, filename).split(sep).join("/")}`;
  entries.push({ src, width, height });
}

const source = [
  "// Generated by scripts/generate-project-image-dimensions.mjs from the local project photos.",
  "// Width and height include EXIF orientation so reserved space matches browser display.",
  "",
  "export const projectImageDimensions: Record<string, { width: number; height: number }> = {",
  ...entries.map(({ src, width, height }) => {
    const key = `  ${JSON.stringify(src)}:`;
    return `${key} {`.length <= 120
      ? `${key} {\n    width: ${width},\n    height: ${height},\n  },`
      : `${key}\n    {\n      width: ${width},\n      height: ${height},\n    },`;
  }),
  "};",
  "",
  "const fallbackDimensions = { width: 1200, height: 900 };",
  "",
  "export function getProjectImageDimensions(src: string) {",
  "  return projectImageDimensions[src] ?? fallbackDimensions;",
  "}",
  "",
].join("\n");

const previousSource = await readFile(outputFile, "utf8").catch((error) => {
  if (error.code === "ENOENT") return "";
  throw error;
});
if (source !== previousSource) await writeFile(outputFile, source, "utf8");

const previewCount = entries.filter(({ src }) => src.endsWith("-preview.webp")).length;
console.log(`Generated dimensions for ${entries.length} project images, including ${previewCount} prepared previews.`);
